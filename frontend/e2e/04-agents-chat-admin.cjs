const { chromium } = require('playwright');
const S = process.argv[2];
const check = (cond, msg) => { if (!cond) throw new Error('CHECK FAILED: ' + msg); console.log('ok -', msg); };
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  global.__page = page;
  const errors = [];
  page.on('pageerror', e => errors.push('pageerror: ' + e.message));
  page.on('console', m => { if (m.type() === 'error' && !m.text().includes('401')) errors.push('console: ' + m.text()); });
  page.on('dialog', d => d.accept());
  const dlg = page.locator('[role=dialog]');
  const field = (label) => page.locator('label', { has: page.locator(`span:text-is("${label}")`) }).locator('input,textarea,select').last();
  await page.goto('' + (process.env.E2E_BASE_URL || 'http://localhost:5173') + '/');
  await page.fill('input[type=email]', 'admin@example.com');
  await page.fill('input[type=password]', 'wrong');
  await page.click('button[type=submit]');
  await page.waitForSelector('text=Invalid email or password');
  check(true, 'wrong password rejected');
  await page.fill('input[type=password]', 'Admin#Passw0rd!');
  await page.click('button[type=submit]');
  await page.waitForSelector('text=Your workflows');
  // Agents: create with Calculate, try it
  await page.click('nav >> text=Agents');
  await page.click('text=New agent');
  await field('Name').fill('Finance Helper');
  await field('Description').fill('Arithmetic for finance');
  await dlg.getByText('Calculate', { exact: true }).click();
  await field('Who can use it').selectOption('public');
  await dlg.locator('button:has-text("Save")').click();
  await page.waitForSelector('h3:has-text("Finance Helper")');
  await page.click('button:has-text("Try")');
  await dlg.locator('textarea').fill('What is 1200 * 0.18 + 40?');
  await dlg.locator('button:has-text("Run")').click();
  await dlg.locator('text=256').first().waitFor();
  check(true, 'agent called Calculate and answered 256');
  await page.keyboard.press('Escape');
  // Chat: AI routing by agent name + general answer
  await page.click('nav >> text=Chat');
  await page.fill('textarea', 'Finance Helper: 2500 * 0.18');
  await page.keyboard.press('Enter');
  await page.waitForSelector('text=AI routed');
  await page.fill('textarea', 'hello there');
  await page.keyboard.press('Enter');
  await page.waitForSelector('text=general assistant');
  check(true, 'chat routes to an agent and falls back to general answers');
  // Admin pages
  await page.click('nav >> text=Models');
  await page.locator('button:has-text("Test")').first().click();
  await page.waitForSelector('text=replied');
  check(true, 'model provider connectivity test');
  await page.click('nav >> text=Users');
  await page.click('text=Add user');
  await field('Email').fill('new.builder@example.com');
  await field('Initial password').fill('Builder#Pass123');
  await field('Role').selectOption('developer');
  await page.locator('[role=dialog] button:has-text("Save")').click();
  await page.waitForSelector('text=new.builder@example.com');
  check(true, 'admin creates a user');
  await page.click('nav >> text=Audit log');
  await page.waitForSelector('text=user.create');
  check(true, 'audit log records user creation');
  await page.click('nav >> text=Monitoring');
  await page.waitForSelector('text=Success rate');
  check(true, 'monitoring metrics render');
  // Builder role cannot see admin pages
  await page.click('text=Sign out');
  await page.fill('input[type=email]', 'new.builder@example.com');
  await page.fill('input[type=password]', 'Builder#Pass123');
  await page.click('button[type=submit]');
  await page.waitForSelector('text=Your workflows');
  const nav = await page.locator('nav').innerText();
  check(!nav.includes('Users') && !nav.includes('Settings') && nav.includes('Connections'), 'developer navigation hides admin pages: ' + nav.replace(/\n/g, ' | '));
  // The session survives a reload without the stored access token (HttpOnly refresh cookie)...
  await page.evaluate(() => localStorage.removeItem('agentos.token'));
  await page.reload();
  await page.waitForSelector('text=Your workflows');
  check(true, 'session resumes from the refresh cookie after reload');
  // ...and signing out ends it on the server: a reload shows the sign-in page.
  await page.click('text=Sign out');
  await page.waitForSelector('button[type=submit]');
  await page.reload();
  await page.waitForSelector('button[type=submit]');
  check(await page.locator('text=Your workflows').count() === 0, 'sign-out ends the server session');
  console.log('ERRORS:', errors.length ? errors.join('\n') : 'none');
  await browser.close();
})().catch(async e => { console.error('E2E FAILED:', e.message.split('\n')[0]); try { await global.__page.screenshot({ path: S + '/fail.png' }); } catch {} process.exit(1); });
